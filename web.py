    def do_POST(self):
        if self.path != "/ask":
            self._send(404, "text/plain; charset=utf-8", b"not found")
            return
        try:
            payload = self._read_json()
        except _BodyError as e:
            self._send(e.code, "application/json",
                       json.dumps({"error": e.message}).encode("utf-8"))
            return
        self._ask(payload)

    def _read_json(self):
        """Read the request body exactly once.

        Every POST path must go through this: the body is a stream, so a second
        read() returns nothing and blocks until the client times out.
        """
        if self.headers.get("Transfer-Encoding"):
            raise _BodyError(400, "chunked request bodies are not supported")
        raw_length = self.headers.get("Content-Length")
        if raw_length is None:
            return {}
        try:
            length = int(raw_length)
        except (TypeError, ValueError):
            raise _BodyError(400, "invalid Content-Length") from None
        if length < 0:
            raise _BodyError(400, "invalid Content-Length")
        if length == 0:
            return {}
        if length > MAX_BODY_BYTES:
            raise _BodyError(413, "request body too large")
        body = self.rfile.read(length)
        if len(body) != length:
            raise _BodyError(400, "incomplete request body")
        try:
            payload = json.loads(body)
        except Exception:
            return None
        return payload if isinstance(payload, dict) else None

    def _ask(self, payload):
        if payload is None:
            self._send(400, "application/json",
                       json.dumps({"error": "bad request"}).encode("utf-8"))
            return
        llm_config = self._llm_for_request()
        if llm_config is _LLM_REJECTED:
            return
        try:
            question = payload.get("question", "").strip()
            mode = payload.get("mode", "ask")
            if mode not in ("ask", "search"):
                mode = "ask"
            sort = payload.get("sort", "relevance")
            if sort not in graph.SEARCH_SORTS:
                sort = "relevance"
            filters = _filters_from_payload(payload)
            deep_verify = bool(payload.get("deep_verify", True))
            # evidence scoring is ask-mode only; search stays a plain listing
            score_evidence = bool(payload.get("score_evidence", False)) and mode == "ask"
            # None = keep the mode default (on for answers, off for search)
            screening = payload.get("screen_retractions")
            screen_retractions = None if screening is None else bool(screening)
            target_species = str(payload.get("target_species") or "").strip()
            saved = scoring.load_settings(self._identity())
            weights = scoring.normalize_weights(
                payload.get("weights") or saved["weights"],
                target_species or saved.get("target_species", ""),
            )
            if not target_species:
                target_species = saved.get("target_species", "")
        except Exception:
            self._send(400, "application/json",
                       json.dumps({"error": "bad request"}).encode("utf-8"))
            return
        if not question:
            self._send(400, "application/json",
                       json.dumps({"error": "empty question"}).encode("utf-8"))
            return
        job_id = _job_id()
        job = {
            "id": job_id,
            "thread_id": job_id,          # LangGraph checkpoint thread
            "question": question, "mode": mode, "sort": sort, "filters": filters,
            "deep_verify": deep_verify, "score_evidence": score_evidence,
            "screen_retractions": screen_retractions,
            "weights": weights, "target_species": target_species,
            "status": "queued", "stage": "排队中…", "log": [], "stages": [],
        }
        _enqueue(job, self._identity(), llm_config=llm_config)
        self._send(202, "application/json",
                   json.dumps({"id": job["id"], "status": "queued"}).encode("utf-8"))

    def _citegraph(self, payload):
        """One paper -> its citation neighbourhood (see citationgraph.py).

        Built synchronously rather than through the job queue: it is a handful
        of OpenAlex requests (measured 3-10s) and the reader is staring at
        exactly this one thing, so handing back a job id to poll would only add
        latency. The request writes nothing, so it needs no owner: the answer is
        the same public data for everybody.
        """
        seed = str((payload or {}).get("seed") or "").strip()[:400]
        if not seed:
            self._send(400, "application/json", json.dumps(
                {"error": "请输入 DOI、OpenAlex ID、论文标题，或一个研究主题"},
                ensure_ascii=False).encode("utf-8"))
            return
        if not self._graph_start("citegraph"):
            return
        try:
            try:
                built = citationgraph.build(seed)
            except LookupError as e:
                self._send(404, "application/json",
                           json.dumps({"error": str(e)}, ensure_ascii=False).encode("utf-8"))
                return
            except citationgraph.GraphError as e:
                # the network, not the input: 503 so the reader knows to retry
                self._send(503, "application/json",
                           json.dumps({"error": str(e)}, ensure_ascii=False).encode("utf-8"))
                return
            except Exception as e:
                self._send(502, "application/json", json.dumps(
                    {"error": f"图谱构建失败：{type(e).__name__}: {e}"},
                    ensure_ascii=False).encode("utf-8"))
                return
            print("      " + citationgraph.summary(built))
            self._send(200, "application/json", json.dumps(
                {"ok": True, "graph": built}, ensure_ascii=False).encode("utf-8"))
        finally:
            self._graph_done()

    def _poolgraph(self, payload):
        """A whole round of results -> one graph of how they relate.

        The counterpart of /citegraph: instead of "put this one paper back into
        its network", this answers "of the twenty papers I just got, which are
        the same story and what do they all stand on". The browser sends the
        round's papers (DOI + the fields it already has); the server never reads
        the store, so this works for a pool that was re-sorted locally, and for
        a run the reader is merely looking at.

        Synchronous for the same reason /citegraph is: a handful of batched
        requests (measured 5-20s for 20-40 papers) and the reader is waiting on
        exactly this.
        """
        papers = (payload or {}).get("papers")
        if not isinstance(papers, list) or not papers:
            self._send(400, "application/json", json.dumps(
                {"error": "这一轮没有论文可画"}, ensure_ascii=False).encode("utf-8"))
